#include <iostream>
using namespace std;
int main()
{
    int decimal = 41; //10진수
    int octal = 041; //8진수
    int hexadecimal = 0x41; //16진수

    cout << "decimal : " << decimal << endl;
    cout << "octal : " << octal << endl;
    cout << "hexadecimal : " << hexadecimal << endl;

    return 0;
}
